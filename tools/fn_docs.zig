//! Build step: the one-sentence doc of every function the given pages describe, as
//! a Zig table the catalog embeds, so the binary carries the sentences rather than
//! the pages. A function is described by the first table row whose first cell holds
//! its call — `name(args)`, alone or before `WITHIN GROUP (…)`, with no call among
//! its arguments — or a bare `name` beside such a call; or by a paragraph or list
//! item that opens with its calls (joined by `,`, `/` or `and`, each perhaps
//! followed by a parenthesis), the words after them from ` — `, ` is ` or a verb
//! on. The doc is the row's last cell, or those words, to the first `;` or
//! sentence end outside a code span, a leading `aggregate — ` or `window — `
//! dropped.
//!
//! Usage: fn_docs <out.zig> <page.md>...

const std = @import("std");

const Doc = struct { name: []const u8, doc: []const u8, page: []const u8 };

pub fn main() !void {
    var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const args = try std.process.argsAlloc(a);
    if (args.len < 3) return error.Usage;

    var docs = std.array_list.Managed(Doc).init(a);
    for (args[2..]) |page| {
        const text = try std.fs.cwd().readFileAlloc(a, page, 4 << 20);
        const rel = if (std.mem.lastIndexOf(u8, page, "docs/")) |i| page[i + "docs/".len ..] else std.fs.path.basename(page);
        try scanPage(a, rel, text, &docs);
    }

    var aw = std.Io.Writer.Allocating.init(a);
    const w = &aw.writer;
    try w.writeAll("//! Generated by tools/fn_docs.zig from the reference pages; do not edit.\n\n");
    try w.writeAll("pub const Doc = struct { name: []const u8, doc: []const u8, page: []const u8 };\n\n");
    try w.writeAll("pub const docs = [_]Doc{\n");
    for (docs.items) |d| {
        try w.writeAll("    .{ .name = ");
        try zigString(w, d.name);
        try w.writeAll(", .doc = ");
        try zigString(w, d.doc);
        try w.writeAll(", .page = ");
        try zigString(w, d.page);
        try w.writeAll(" },\n");
    }
    try w.writeAll("};\n");
    try std.fs.cwd().writeFile(.{ .sub_path = args[1], .data = aw.written() });
}

fn zigString(w: *std.Io.Writer, s: []const u8) !void {
    try w.writeByte('"');
    for (s) |c| switch (c) {
        '"' => try w.writeAll("\\\""),
        '\\' => try w.writeAll("\\\\"),
        '\n' => try w.writeAll("\\n"),
        0...9, 11...0x1f, 0x7f => try w.print("\\x{x:0>2}", .{c}),
        else => try w.writeByte(c),
    };
    try w.writeByte('"');
}

fn has(docs: []const Doc, name: []const u8) bool {
    for (docs) |d| if (std.mem.eql(u8, d.name, name)) return true;
    return false;
}

fn add(a: std.mem.Allocator, docs: *std.array_list.Managed(Doc), page: []const u8, names: []const []const u8, raw: []const u8) !void {
    const doc = try clause(a, raw);
    if (doc.len == 0) return;
    for (names) |n| if (!has(docs.items, n)) try docs.append(.{ .name = n, .doc = doc, .page = page });
}

/// One page's described functions: its table rows, then its paragraphs and list
/// items, fenced blocks skipped.
fn scanPage(a: std.mem.Allocator, page: []const u8, text: []const u8, docs: *std.array_list.Managed(Doc)) !void {
    var para = std.array_list.Managed(u8).init(a);
    var fenced = false;
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = std.mem.trim(u8, raw, " \t\r");
        if (std.mem.startsWith(u8, line, "```")) {
            fenced = !fenced;
            try flush(a, page, &para, docs);
            continue;
        }
        if (fenced) continue;
        if (line.len == 0 or line[0] == '#' or line[0] == '|') {
            try flush(a, page, &para, docs);
            if (line.len > 0 and line[0] == '|') try tableRow(a, page, line, docs);
            continue;
        }
        if (std.mem.startsWith(u8, line, "- ")) try flush(a, page, &para, docs);
        if (para.items.len > 0) try para.append(' ');
        try para.appendSlice(line);
    }
    try flush(a, page, &para, docs);
}

fn flush(a: std.mem.Allocator, page: []const u8, para: *std.array_list.Managed(u8), docs: *std.array_list.Managed(Doc)) !void {
    defer para.clearRetainingCapacity();
    var s: []const u8 = para.items;
    if (std.mem.startsWith(u8, s, "- ")) s = s[2..];
    var names = std.array_list.Managed([]const u8).init(a);
    while (s.len > 0 and s[0] == '`') {
        const close = std.mem.indexOfScalarPos(u8, s, 1, '`') orelse return;
        const n = callName(a, s[1..close]) orelse return;
        try names.append(n);
        s = s[close + 1 ..];
        if (std.mem.startsWith(u8, s, " (")) if (std.mem.indexOfScalar(u8, s, ')')) |p| {
            s = s[p + 1 ..];
        };
        for ([_][]const u8{ ", ", " / ", " and " }) |sep| {
            if (std.mem.startsWith(u8, s, sep) and s.len > sep.len and s[sep.len] == '`') {
                s = s[sep.len..];
                break;
            }
        }
    }
    if (names.items.len == 0) return;
    for ([_][]const u8{ " — ", " is ", " are " }) |lead| {
        if (std.mem.startsWith(u8, s, lead)) return add(a, docs, page, names.items, s[lead.len..]);
    }
    if (s.len > 1 and s[0] == ' ' and std.ascii.isLower(s[1])) return add(a, docs, page, names.items, s[1..]);
}

/// A row's described functions and its last cell; the header row and the rule under
/// it describe none.
fn tableRow(a: std.mem.Allocator, page: []const u8, line: []const u8, docs: *std.array_list.Managed(Doc)) !void {
    var cells = std.array_list.Managed([]const u8).init(a);
    var start: usize = 1;
    var i: usize = 1;
    while (i < line.len) : (i += 1) {
        if (line[i] == '\\') {
            i += 1;
        } else if (line[i] == '|') {
            try cells.append(std.mem.trim(u8, line[start..i], " "));
            start = i + 1;
        }
    }
    if (cells.items.len < 2) return;
    const first = cells.items[0];
    var calls = std.array_list.Managed([]const u8).init(a);
    var bare = std.array_list.Managed([]const u8).init(a);
    var k: usize = 0;
    while (std.mem.indexOfScalarPos(u8, first, k, '`')) |open| {
        const close = std.mem.indexOfScalarPos(u8, first, open + 1, '`') orelse break;
        const span = first[open + 1 .. close];
        if (callName(a, span)) |n| try calls.append(n) else if (isIdent(span)) try bare.append(try std.ascii.allocLowerString(a, span));
        k = close + 1;
    }
    if (calls.items.len == 0) return;
    try calls.appendSlice(bare.items);
    try add(a, docs, page, calls.items, cells.items[cells.items.len - 1]);
}

fn isIdent(s: []const u8) bool {
    if (s.len < 2 or !(std.ascii.isAlphabetic(s[0]) or s[0] == '_')) return false;
    for (s) |c| if (!(std.ascii.isAlphanumeric(c) or c == '_')) return false;
    return true;
}

/// The function a code span calls, lower-cased, when the span is a call: a name,
/// its argument list holding no call of its own, then nothing or `WITHIN GROUP (…)`.
fn callName(a: std.mem.Allocator, span: []const u8) ?[]const u8 {
    var n: usize = 0;
    while (n < span.len and (std.ascii.isAlphanumeric(span[n]) or span[n] == '_')) n += 1;
    if (n < 2 or n >= span.len or span[n] != '(' or std.ascii.isDigit(span[0])) return null;
    var depth: usize = 0;
    var end: ?usize = null;
    for (span[n..], n..) |c, i| {
        if (c == '(') {
            if (depth > 0 and i > 0 and (std.ascii.isAlphanumeric(span[i - 1]) or span[i - 1] == '_')) return null;
            depth += 1;
        } else if (c == ')') {
            depth -= 1;
            if (depth == 0) {
                end = i;
                break;
            }
        }
    }
    const close = end orelse return null;
    const tail = std.mem.trim(u8, span[close + 1 ..], " ");
    if (tail.len > 0 and !std.mem.startsWith(u8, tail, "WITHIN GROUP")) return null;
    const args = std.mem.trim(u8, span[n + 1 .. close], " ");
    if (std.mem.eql(u8, args, "...") or std.mem.startsWith(u8, args, "DISTINCT ")) return null;
    return std.ascii.allocLowerString(a, span[0..n]) catch null;
}

/// The first clause of a description: up to its first `;` or sentence end outside a
/// code span, a kind's lead-in dropped, starting upper case and ending in a period.
fn clause(a: std.mem.Allocator, raw: []const u8) ![]const u8 {
    var s = std.mem.trim(u8, raw, " ");
    for ([_][]const u8{ "aggregate — ", "window — " }) |lead| {
        if (std.mem.startsWith(u8, s, lead)) s = s[lead.len..];
    }
    var code = false;
    var end = s.len;
    for (s, 0..) |c, i| {
        if (c == '`') code = !code;
        if (code) continue;
        const next_blank = i + 1 == s.len or s[i + 1] == ' ';
        if (c == ';' or (c == '.' and next_blank)) {
            end = i;
            break;
        }
    }
    const body = std.mem.trim(u8, s[0..end], " ,");
    if (body.len == 0) return "";
    var out = std.array_list.Managed(u8).init(a);
    for (body, 0..) |c, i| {
        if (c == '\\' and i + 1 < body.len and body[i + 1] == '|') continue;
        try out.append(c);
    }
    if (std.ascii.isLower(out.items[0])) out.items[0] = std.ascii.toUpper(out.items[0]);
    try out.append('.');
    return out.toOwnedSlice();
}

test "callName: a call, a call before WITHIN GROUP, and spans that describe no one function" {
    var ar = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer ar.deinit();
    const a = ar.allocator();
    try std.testing.expectEqualStrings("substr", callName(a, "substr(s, start[, length])").?);
    try std.testing.expectEqualStrings("percentile_cont", callName(a, "percentile_cont(f) WITHIN GROUP (ORDER BY x)").?);
    try std.testing.expectEqualStrings("json_reduce", callName(a, "JSON_REDUCE(arr, initial, (acc, x) -> value)").?);
    for ([_][]const u8{ "ROUND(AVG(x), 2)", "SUM(x) FILTER (WHERE cond)", "COUNT(*) / SUM / AVG", "f(...) OVER (…)", "COUNT(DISTINCT x)", "a || b", "x'0D0A'" }) |s|
        try std.testing.expect(callName(a, s) == null);
}

test "clause: up to the first semicolon or sentence end outside code, capitalised, a period after" {
    var ar = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer ar.deinit();
    const a = ar.allocator();
    try std.testing.expectEqualStrings("The number of characters.", try clause(a, "the number of characters"));
    try std.testing.expectEqualStrings("The rows where `cond` is true, as an `INT`.", try clause(a, "aggregate — the rows where `cond` is true, as an `INT`; `0` for no rows"));
    try std.testing.expectEqualStrings("Rows of `t.*` and `0.5`.", try clause(a, "rows of `t.*` and `0.5`. More here"));
    try std.testing.expectEqualStrings("`a | b` joined.", try clause(a, "`a \\| b` joined"));
}
