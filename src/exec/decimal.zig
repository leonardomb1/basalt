//! The one home of DECIMAL logic: the `Decimal` type, its powers of ten, checked
//! arithmetic and result typing, rescaling and rounding, text, the binary layouts
//! wires and files store an unscaled integer in, and the exact-integer key reading.
//!
//! A `Decimal` is exact, `unscaled * 10^-scale`, and each value carries its own
//! scale, which need not equal its column's declared one (PostgreSQL sends a
//! per-value `dscale`): anything combining decimals across rows normalizes first.
//! Its i128 field is `align(8)` on purpose: natural 16-byte alignment would size
//! the whole `Value` union at 48 bytes, so every bool and i64 would pay for a
//! decimal it does not hold; relaxed, `Value` is 32 bytes, and x86 handles the
//! unaligned access on a cold path.
//!
//! `pow10_table` is generated by the repeated multiplication the old runtime loop
//! did, so each entry is bit-identical to what that loop returned; it exists
//! because `keyhash.hashValue` folds every decimal key through `Decimal.keyF64`
//! per row.
//!
//! Callers keep their own error mapping (a reader's corrupt-file error, a writer's
//! overflow naming the column); what lives here answers null where it cannot.

const std = @import("std");
const ast = @import("../lang/ast.zig");
const types = @import("../lang/types.zig");
const Value = @import("value.zig").Value;
const Type = types.Type;
const failWith = @import("eval/support.zig").failWith;
const trim = @import("eval/support.zig").trim;
const fmt_bound = @import("eval/format.zig").fmt_bound;

pub const Decimal = struct {
    unscaled: i128 align(8),
    scale: u8,

    pub fn toF64(self: Decimal) f64 {
        return @as(f64, @floatFromInt(self.unscaled)) / pow10f(self.scale);
    }

    /// The f64 a decimal hashes and meets a float as. Equal decimals at any scale
    /// give the same bits: exact operands divide to the one correctly rounded
    /// quotient, and anything wider is reduced to its shortest scale first.
    pub fn keyF64(self: Decimal) f64 {
        const exact_int: i128 = 1 << 53;
        if (self.scale <= 22 and self.unscaled < exact_int and self.unscaled > -exact_int) return self.toF64();
        var d = self;
        while (d.scale > 0 and @rem(d.unscaled, 10) == 0) {
            d.unscaled = @divTrunc(d.unscaled, 10);
            d.scale -= 1;
        }
        return d.toF64();
    }

    /// Exact order: the lower scale is raised to the higher in i256. A side that
    /// overflows doing so is larger in magnitude than any i128, so its sign decides.
    pub fn order(a: Decimal, b: Decimal) std.math.Order {
        if (a.scale == b.scale) return std.math.order(a.unscaled, b.unscaled);
        const up_a = a.scale < b.scale;
        const diff: u8 = if (up_a) b.scale - a.scale else a.scale - b.scale;
        const raised: i128 = if (up_a) a.unscaled else b.unscaled;
        if (diff < 39) if (std.math.mul(i128, raised, pow10_i128[diff])) |r| {
            return if (up_a) std.math.order(r, b.unscaled) else std.math.order(a.unscaled, r);
        } else |_| {};
        const other: i256 = if (up_a) b.unscaled else a.unscaled;
        const big: i256 = if (diff < pow10_i256.len)
            std.math.mul(i256, raised, pow10_i256[diff]) catch @as(i256, std.math.sign(raised)) * std.math.maxInt(i256)
        else if (raised == 0) 0 else @as(i256, std.math.sign(raised)) * std.math.maxInt(i256);
        return if (up_a) std.math.order(big, other) else std.math.order(other, big);
    }
};

pub const pow10_i128 = blk: {
    var t: [39]i128 = undefined;
    var r: i128 = 1;
    for (&t) |*e| {
        e.* = r;
        r *%= 10;
    }
    break :blk t;
};

pub const pow10_i256 = blk: {
    var t: [76]i256 = undefined;
    var r: i256 = 1;
    for (&t) |*e| {
        e.* = r;
        r *= 10;
    }
    break :blk t;
};

const pow10_table = blk: {
    var t: [39]f64 = undefined;
    var r: f64 = 1;
    for (&t) |*e| {
        e.* = r;
        r *= 10;
    }
    break :blk t;
};

pub fn pow10f(n: u8) f64 {
    if (n < pow10_table.len) return pow10_table[n];
    var r: f64 = pow10_table[pow10_table.len - 1];
    var k: u8 = pow10_table.len - 1;
    while (k < n) : (k += 1) r *= 10;
    return r;
}

pub const max_digits = 38;

pub fn decimalOverflow() error{IntOverflow} {
    return @errorCast(failWith(error.IntOverflow, "decimal overflow: more than 38 digits", .{}));
}

/// Whether `u` has at most `p` digits; precision 0, a driver's "unknown", is 38.
pub fn fitsPrecision(u: i128, p: u8) bool {
    const digits: u8 = if (p == 0 or p > max_digits) max_digits else p;
    return @abs(u) < @as(u128, @intCast(pow10_i128[digits]));
}

/// Whether an unscaled decimal has at most `precision` digits, taken as given
/// (no "unknown" 0), as a file's declared precision is.
pub fn withinPrecision(v: i128, precision: u8) bool {
    const bound = pow10_i128[precision];
    return v < bound and v > -bound;
}

/// `u / 10^drop` for an i128 or i256 `u`, rounded half away from zero.
pub fn roundScaleDown(u: anytype, drop: u32) @TypeOf(u) {
    const table = if (@TypeOf(u) == i128) &pow10_i128 else &pow10_i256;
    if (drop >= table.len) return 0;
    const p = table[drop];
    const q = @divTrunc(u, p);
    if (@abs(@rem(u, p)) * 2 >= @abs(p)) return if (u < 0) q - 1 else q + 1;
    return q;
}

/// Shifts a decimal to `want`, rounding half away from zero; null on overflow.
/// Public because a value's scale need not match its column's (Postgres sends a
/// per-value `dscale`), so anything combining decimals across rows normalizes first.
pub fn rescaleTo(d: Decimal, want: u8) ?Decimal {
    var unscaled = d.unscaled;
    var have: i32 = d.scale;
    while (have < want) : (have += 1) {
        unscaled = std.math.mul(i128, unscaled, 10) catch return null;
    }
    if (have > want) unscaled = roundScaleDown(unscaled, @intCast(have - want));
    return .{ .unscaled = unscaled, .scale = want };
}

/// The unscaled integer restated at `want` as a `T`; null when it overflows either.
pub fn rescaleAs(comptime T: type, d: Decimal, want: u8) ?T {
    const r = rescaleTo(d, want) orelse return null;
    return std.math.cast(T, r.unscaled);
}

/// Adds `d` to a DECIMAL SUM's wide total, at the sum's `scale`. The add needs no
/// check: each addend is an i128, so fewer than 2^63 of them (a state's i64 count)
/// stay under 2^191, far inside i256.
pub inline fn addAtScale(sum: *align(8) i256, d: Decimal, scale: u8) error{IntOverflow}!void {
    const u = if (d.scale == scale) d.unscaled else (rescaleTo(d, scale) orelse return decimalOverflow()).unscaled;
    sum.* += u;
}

/// A DECIMAL SUM's wide total as a 38-digit decimal at `scale`, null past 38 digits.
/// Sums add in i256 and only the total is range-checked, as PostgreSQL's NUMERIC
/// sum is exact, so no batch split or row order can fail a sum that fits.
pub fn wideSumDecimal(total: i256, scale: u8) ?Decimal {
    const u = std.math.cast(i128, total) orelse return null;
    return if (fitsPrecision(u, max_digits)) .{ .unscaled = u, .scale = scale } else null;
}

/// The scale `round(decimal, digits)` answers in: the digits when they are a
/// literal (as DuckDB types it; a negative one is scale 0), else the input's own.
pub fn roundOutScale(c: ast.Expr.Call, in_scale: u8) u8 {
    if (c.args.len < 2) return 0;
    const d = c.args[1];
    if (d.* == .unary and d.unary.op == .neg and d.unary.e.* == .int_lit) return 0;
    if (d.* != .int_lit) return in_scale;
    return @intCast(std.math.clamp(d.int_lit, 0, in_scale));
}

pub fn roundDecimal(d: Decimal, digits: i64, out_scale: u8) ?Decimal {
    var r = d;
    if (digits < d.scale) {
        const drop = @as(i64, d.scale) - digits;
        if (drop > 38) return .{ .unscaled = 0, .scale = out_scale };
        var q = roundScaleDown(d.unscaled, @intCast(drop));
        if (digits < 0) {
            q = std.math.mul(i128, q, pow10_i128[@intCast(@min(-digits, 38))]) catch return null;
            r = .{ .unscaled = q, .scale = 0 };
        } else r = .{ .unscaled = q, .scale = @intCast(digits) };
    }
    return rescaleTo(r, out_scale);
}

pub fn abs(d: Decimal) Decimal {
    return .{ .unscaled = if (d.unscaled < 0) -d.unscaled else d.unscaled, .scale = d.scale };
}

/// `floor` (`down`) or `ceil`, exactly to scale 0.
pub fn whole(comptime down: bool, d: Decimal) Decimal {
    if (d.scale >= pow10_i128.len) return .{ .unscaled = 0, .scale = 0 };
    const p = pow10_i128[d.scale];
    var q = @divTrunc(d.unscaled, p);
    if (@rem(d.unscaled, p) != 0) {
        if (down and d.unscaled < 0) q -= 1;
        if (!down and d.unscaled > 0) q += 1;
    }
    return .{ .unscaled = q, .scale = 0 };
}

pub fn wholeType(t: Type) Type {
    return Type.decimal(@min(38, (t.precision -| t.scale) + 1), 0);
}

pub fn sign(d: Decimal) Decimal {
    return .{ .unscaled = std.math.sign(d.unscaled), .scale = 0 };
}

/// Seconds as whole microseconds: raised exactly, or cut to scale 6 with only the
/// last dropped digit rounding half away from zero. Null past i64.
pub fn toMicros(d: Decimal) ?i64 {
    var q: i128 = d.unscaled;
    var s: u8 = d.scale;
    while (s < 6) : (s += 1) q = std.math.mul(i128, q, 10) catch return null;
    while (s > 6) : (s -= 1) q = @divTrunc(q + (if (s == 7) @as(i128, if (q < 0) -5 else 5) else 0), 10);
    return std.math.cast(i64, q);
}

/// The i64 a decimal equals exactly; null when it has a fraction or passes i64.
pub fn exactInt(d: Decimal) ?i64 {
    if (d.scale >= pow10_i128.len) return if (d.unscaled == 0) 0 else null;
    const p = pow10_i128[d.scale];
    if (@rem(d.unscaled, p) != 0) return null;
    return std.math.cast(i64, @divExact(d.unscaled, p));
}

pub fn asDecimal(v: Value) ?Decimal {
    return switch (v) {
        .decimal => |d| d,
        .int => |x| .{ .unscaled = x, .scale = 0 },
        else => null,
    };
}

/// The decimal a value reads as before it meets a target's scale and precision.
pub fn asDecimalValue(v: Value) ?Decimal {
    return switch (v) {
        .decimal => |x| x,
        .int => |x| .{ .unscaled = x, .scale = 0 },
        .bool => |x| .{ .unscaled = if (x) 1 else 0, .scale = 0 },
        .float => |x| floatToDecimal(x),
        .string, .bytes => |str| parse(trim(str)),
        else => null,
    };
}

/// A float as the decimal its 15 significant digits spell, as PostgreSQL casts
/// float8 to numeric. Null for a non-finite value or one past 38 digits.
pub fn floatToDecimal(x: f64) ?Decimal {
    if (!std.math.isFinite(x)) return null;
    if (x == 0) return .{ .unscaled = 0, .scale = 0 };
    var buf: [48]u8 = undefined;
    const s = std.fmt.bufPrint(&buf, "{e:.14}", .{@abs(x)}) catch return null;
    const e_at = std.mem.indexOfScalar(u8, s, 'e') orelse return null;
    var m: i128 = 0;
    for (s[0..e_at]) |c| {
        if (c == '.') continue;
        m = m * 10 + (c - '0');
    }
    const exp = std.fmt.parseInt(i32, s[e_at + 1 ..], 10) catch return null;
    if (x < 0) m = -m;
    const shift = exp - 14;
    if (shift >= 0) {
        if (shift > 23) return null;
        return .{ .unscaled = std.math.mul(i128, m, pow10_i128[@intCast(shift)]) catch return null, .scale = 0 };
    }
    const sc = -shift;
    if (sc <= 38) return .{ .unscaled = m, .scale = @intCast(sc) };
    return .{ .unscaled = roundScaleDown(m, @intCast(sc - 38)), .scale = 38 };
}

/// The exact DECIMAL type of `op`, or null when it stays float. `+ - %` take the
/// wider scale, `*` the summed scale; an INT operand is a DECIMAL(19,0). A
/// quotient's scale is the operands' wider one but at least 16 while its whole
/// digits leave room; each value carries the finer scale `decimalDiv` picks.
pub fn decimalArithType(op: ast.BinOp, lt: Type, rt: Type) ?Type {
    switch (op) {
        .add, .sub, .mul, .div, .mod => {},
        else => return null,
    }
    if (lt.kind == .float or rt.kind == .float) return null;
    if (lt.kind != .decimal and rt.kind != .decimal) return null;
    const lp: u16 = if (lt.kind != .decimal) 19 else if (lt.precision == 0) 38 else lt.precision;
    const rp: u16 = if (rt.kind != .decimal) 19 else if (rt.precision == 0) 38 else rt.precision;
    const ls: u16 = if (lt.kind == .decimal) lt.scale else 0;
    const rs: u16 = if (rt.kind == .decimal) rt.scale else 0;
    const whole_digits = (lp -| ls) + rs;
    const scale: u16 = switch (op) {
        .mul => ls + rs,
        .div => @max(ls, rs, @min(div_min_digits, max_digits -| whole_digits)),
        else => @max(ls, rs),
    };
    const prec: u16 = switch (op) {
        .mul => lp + rp,
        .div => whole_digits + scale,
        .mod => @max(1, @min(lp -| ls, rp -| rs) + scale),
        else => @max(lp -| ls, rp -| rs) + scale + 1,
    };
    return Type.decimal(@intCast(@min(38, prec)), @intCast(@min(38, scale)));
}

const div_min_digits = 16;

/// `a / b` as PostgreSQL's numeric division answers it (`select_div_scale`): at
/// least 16 significant digits, judged from the operands' leading base-10000
/// digits, and no fewer scale digits than either operand, rounded half away from
/// zero. Past 38 digits in all, the scale gives way first.
pub fn decimalDiv(a: Decimal, b: Decimal) error{ IntOverflow, DivByZero }!Decimal {
    if (b.unscaled == 0) return error.DivByZero;
    const wa = pgWeight(a);
    const wb = pgWeight(b);
    var qweight = wa.weight - wb.weight;
    if (wa.first <= wb.first) qweight -= 1;
    const rscale: i32 = @max(div_min_digits - qweight * 4, a.scale, b.scale, 0);
    var scale: u8 = @intCast(@min(rscale, max_digits));
    while (true) {
        const q = quotientAt(a, b, scale);
        const excess = excessDigits(q);
        if (excess == 0) return .{ .unscaled = @intCast(q), .scale = scale };
        if (scale < excess) return decimalOverflow();
        scale -= excess;
    }
}

/// A decimal's PostgreSQL weight (the power of 10000 of its leading base-10000
/// digit) and that digit; a zero is weight 0, digit 0.
fn pgWeight(d: Decimal) struct { weight: i32, first: u256 } {
    const u: u256 = @abs(d.unscaled);
    if (u == 0) return .{ .weight = 0, .first = 0 };
    var n: i32 = 1;
    while (n < pow10_i256.len and u >= @as(u256, @intCast(pow10_i256[@intCast(n)]))) n += 1;
    const weight = @divFloor(n - 1 - @as(i32, d.scale), 4);
    const shift = weight * 4 + d.scale;
    const first = if (shift >= 0) u / @as(u256, @intCast(pow10_i256[@intCast(shift)])) else u * @as(u256, @intCast(pow10_i256[@intCast(-shift)]));
    return .{ .weight = weight, .first = first };
}

/// `a / b` at `scale`, rounded half away from zero. i256 holds every case whose
/// dividend is raised by at most 38 places; only a wider shift pays for i512.
fn quotientAt(a: Decimal, b: Decimal, scale: u8) i512 {
    const e: i32 = @as(i32, scale) + b.scale - a.scale;
    if (e <= max_digits) return roundedQuotient(i256, a.unscaled, b.unscaled, e);
    return roundedQuotient(i512, a.unscaled, b.unscaled, e);
}

fn roundedQuotient(comptime T: type, x: i128, y: i128, e: i32) T {
    var n: T = x;
    var d: T = y;
    if (e >= 0) n *= pow10Of(T, @intCast(e)) else d *= pow10Of(T, @intCast(-e));
    const q = @divTrunc(n, d);
    const r = @rem(n, d);
    if (@abs(r) * 2 >= @abs(d)) return if ((n < 0) != (d < 0)) q - 1 else q + 1;
    return q;
}

fn pow10Of(comptime T: type, n: u16) T {
    if (n < pow10_i256.len) return pow10_i256[n];
    var r: T = pow10_i256[pow10_i256.len - 1];
    for (pow10_i256.len - 1..n) |_| r *= 10;
    return r;
}

/// How many digits `q` has past 38; 0 when it fits.
fn excessDigits(q: i512) u8 {
    var k: u8 = 0;
    const u = @abs(q);
    while (u >= @as(u512, @intCast(pow10Of(i512, max_digits + k)))) k += 1;
    return k;
}

/// `*` multiplies in i256 so a product past scale 38 can round back to it before
/// the 38-digit check; any result wider than 38 digits is a decimal overflow.
pub fn decimalOp(op: ast.BinOp, a: Decimal, b: Decimal) ?error{ IntOverflow, DivByZero }!Decimal {
    const r: Decimal = switch (op) {
        .mul => blk: {
            const s = @as(u16, a.scale) + b.scale;
            if (s <= max_digits) if (std.math.mul(i128, a.unscaled, b.unscaled)) |u| break :blk .{ .unscaled = u, .scale = @intCast(s) } else |_| {};
            const p = @as(i256, a.unscaled) * b.unscaled;
            const drop = s -| max_digits;
            const q = roundScaleDown(p, drop);
            break :blk .{ .unscaled = std.math.cast(i128, q) orelse return decimalOverflow(), .scale = @intCast(s - drop) };
        },
        .add, .sub => blk: {
            const s = @max(a.scale, b.scale);
            const x = rescaleTo(a, s) orelse return decimalOverflow();
            const y = rescaleTo(b, s) orelse return decimalOverflow();
            const u = if (op == .add) std.math.add(i128, x.unscaled, y.unscaled) else std.math.sub(i128, x.unscaled, y.unscaled);
            break :blk .{ .unscaled = u catch return decimalOverflow(), .scale = s };
        },
        .div => try decimalDiv(a, b),
        .mod => blk: {
            const s = @max(a.scale, b.scale);
            const x = rescaleTo(a, s) orelse return decimalOverflow();
            const y = rescaleTo(b, s) orelse return decimalOverflow();
            if (y.unscaled == 0) return error.DivByZero;
            break :blk .{ .unscaled = @rem(x.unscaled, y.unscaled), .scale = s };
        },
        else => return null,
    };
    if (!fitsPrecision(r.unscaled, max_digits)) return decimalOverflow();
    return r;
}

pub const Bound = struct { op: ast.BinOp, bound: i128 };

/// A comparison against constant `d` at a column's scale `sc` (`x > 2.5` over INT
/// is `x > 2`): the operator and whole bound that decide the same rows, with the
/// constant on the right. `never` is a bound no element falls below. Null when
/// the bound passes i128.
pub fn cmpBound(op: ast.BinOp, flip: bool, d: Decimal, sc: u8, never: i128) ?Bound {
    var fl: i128 = undefined;
    var exact = true;
    if (d.scale <= sc) {
        fl = std.math.mul(i128, d.unscaled, pow10_i128[sc - d.scale]) catch return null;
    } else {
        if (d.scale - sc >= pow10_i128.len) return null;
        const p = pow10_i128[d.scale - sc];
        fl = @divFloor(d.unscaled, p);
        exact = @mod(d.unscaled, p) == 0;
    }
    const ce = if (exact) fl else fl + 1;
    const o: ast.BinOp = if (!flip) op else switch (op) {
        .lt => .gt,
        .le => .ge,
        .gt => .lt,
        .ge => .le,
        else => op,
    };
    return switch (o) {
        .gt => .{ .op = .gt, .bound = fl },
        .ge => .{ .op = .ge, .bound = ce },
        .lt => .{ .op = .lt, .bound = ce },
        .le => .{ .op = .le, .bound = fl },
        .eq => if (exact) .{ .op = .eq, .bound = fl } else .{ .op = .lt, .bound = never },
        .ne => if (exact) .{ .op = .ne, .bound = fl } else .{ .op = .ge, .bound = never },
        else => null,
    };
}

/// A decimal literal: optional sign, digits, at most one `.`, at least one digit, else
/// null. It once skipped unknown characters, so `'1000,00'` read as 100000.00 and
/// `'abc'` as 0; comma-decimal data must be rewritten with `replace(x, ',', '.')`.
pub fn parse(t: []const u8) ?Decimal {
    var s = t;
    var neg = false;
    if (s.len > 0 and (s[0] == '-' or s[0] == '+')) {
        neg = s[0] == '-';
        s = s[1..];
    }
    if (s.len == 0) return null;
    var unscaled: i128 = 0;
    var scale: u8 = 0;
    var digits: usize = 0;
    var after_dot = false;
    for (s) |c| {
        if (c == '.') {
            if (after_dot) return null;
            after_dot = true;
            continue;
        }
        if (c < '0' or c > '9') return null;
        unscaled = std.math.mul(i128, unscaled, 10) catch return null;
        unscaled = std.math.add(i128, unscaled, c - '0') catch return null;
        digits += 1;
        if (after_dot) scale += 1;
    }
    if (digits == 0) return null;
    return .{ .unscaled = if (neg) -unscaled else unscaled, .scale = scale };
}

/// Digits are produced with 64-bit division whenever the magnitude fits, and the
/// text is written in one call.
pub fn writeDecimal(w: anytype, unscaled: i128, scale: u8) !void {
    const neg = unscaled < 0;
    var mag: u128 = if (neg) @intCast(-unscaled) else @intCast(unscaled);

    var digits: [48]u8 = undefined;
    var n: usize = 0;
    if (std.math.cast(u64, mag)) |small| {
        var m = small;
        while (true) {
            digits[n] = @intCast('0' + m % 10);
            n += 1;
            m /= 10;
            if (m == 0) break;
        }
    } else {
        while (mag > 0) : (mag /= 10) {
            digits[n] = @intCast('0' + mag % 10);
            n += 1;
        }
    }
    while (n <= scale) : (n += 1) digits[n] = '0';

    var text: [digits.len + 2]u8 = undefined;
    var t: usize = 0;
    if (neg) {
        text[0] = '-';
        t = 1;
    }
    var k: usize = n;
    while (k > 0) {
        k -= 1;
        text[t] = digits[k];
        t += 1;
        if (scale > 0 and k == scale) {
            text[t] = '.';
            t += 1;
        }
    }
    try w.writeAll(text[0..t]);
}

pub fn formatDecimal(arena: std.mem.Allocator, unscaled: i128, scale: u8) ![]const u8 {
    var buf: [fmt_bound]u8 = undefined;
    var w = std.Io.Writer.fixed(&buf);
    writeDecimal(&w, unscaled, scale) catch unreachable;
    return arena.dupe(u8, w.buffered());
}

/// A big-endian two's complement integer as an unscaled decimal; null when it is
/// wider than an i128 holds. Eight bytes or fewer take a 64-bit path.
pub fn bigEndianDecimal(b: []const u8) ?i128 {
    if (b.len == 0) return 0;
    const neg = b[0] & 0x80 != 0;
    if (b.len <= 8) {
        var acc: u64 = if (neg) std.math.maxInt(u64) else 0;
        for (b) |x| acc = (acc << 8) | x;
        return @as(i64, @bitCast(acc));
    }
    var start: usize = 0;
    if (b.len > 16) {
        start = b.len - 16;
        for (b[0..start]) |x| if (x != (if (neg) @as(u8, 0xFF) else 0)) return null;
        if ((b[start] & 0x80 != 0) != neg) return null;
    }
    var acc: u128 = if (neg) std.math.maxInt(u128) else 0;
    for (b[start..]) |x| acc = (acc << 8) | x;
    return @bitCast(acc);
}

/// A sign beside a little-endian magnitude as an unscaled decimal; null when the
/// magnitude is wider than an i128 holds.
pub fn signMagnitudeDecimal(positive: bool, mag: []const u8) ?i128 {
    if (mag.len > 16) return null;
    var u: u128 = 0;
    for (mag, 0..) |b, k| u |= @as(u128, b) << @intCast(k * 8);
    const m = std.math.cast(i128, u) orelse return null;
    return if (positive) m else -m;
}

/// MONEY (8 bytes, high 32-bit word first) or SMALLMONEY (4 bytes), little-endian
/// ten-thousandths; null for any other length.
pub fn money(bytes: []const u8) ?Decimal {
    const unscaled: i64 = switch (bytes.len) {
        4 => std.mem.readInt(i32, bytes[0..4], .little),
        8 => blk: {
            const hi: u64 = @bitCast(@as(i64, std.mem.readInt(i32, bytes[0..4], .little)));
            const lo: u64 = std.mem.readInt(u32, bytes[4..8], .little);
            break :blk @bitCast((hi << 32) | lo);
        },
        else => return null,
    };
    return .{ .unscaled = unscaled, .scale = 4 };
}

/// Big-endian two's complement in exactly `b.len` bytes (a FIXED_LEN_BYTE_ARRAY
/// decimal); false rather than truncating a value the width cannot hold.
pub fn fixedBigEndian(b: []u8, x: i128) bool {
    if (b.len == 0 or b.len > 16) return false;
    var v = x;
    var i = b.len;
    while (i > 0) : (i -= 1) {
        b[i - 1] = @truncate(@as(u128, @bitCast(v)));
        v >>= 8;
    }
    if (v != (if (x < 0) @as(i128, -1) else 0)) return false;
    if ((b[0] & 0x80 != 0) != (x < 0)) return false;
    return true;
}

pub const Minimal = struct { bytes: [16]u8, start: usize };

/// `x` in the fewest big-endian two's complement bytes that hold it: `bytes[start..]`.
pub fn minimalBigEndian(x: i128) Minimal {
    const be = std.mem.toBytes(std.mem.nativeToBig(i128, x));
    var start: usize = 0;
    while (start < 15) : (start += 1) {
        const lead = be[start];
        const next_high = be[start + 1] & 0x80 != 0;
        if (!((lead == 0 and !next_high) or (lead == 0xFF and next_high))) break;
    }
    return .{ .bytes = be, .start = start };
}

const testing = std.testing;

fn writeDecimalReference(w: anytype, unscaled: i128, scale: u8) !void {
    const neg = unscaled < 0;
    var mag: u128 = if (neg) @intCast(-unscaled) else @intCast(unscaled);
    var digits: [48]u8 = undefined;
    var n: usize = 0;
    if (mag == 0) {
        digits[0] = '0';
        n = 1;
    }
    while (mag > 0) : (mag /= 10) {
        digits[n] = @intCast('0' + mag % 10);
        n += 1;
    }
    while (n <= scale) : (n += 1) digits[n] = '0';
    if (neg) try w.writeByte('-');
    var k: usize = n;
    while (k > 0) {
        k -= 1;
        try w.writeByte(digits[k]);
        if (scale > 0 and k == scale) try w.writeByte('.');
    }
}

test "writeDecimal matches the digit-at-a-time 128-bit rendering" {
    var prng = std.Random.DefaultPrng.init(0xdec);
    const rnd = prng.random();
    const edges = [_]i128{ 0, 1, -1, 9, 10, -10, std.math.maxInt(u64), -@as(i128, std.math.maxInt(u64)), @as(i128, std.math.maxInt(u64)) + 1, std.math.maxInt(i128), -std.math.maxInt(i128), std.math.maxInt(i64), std.math.minInt(i64) };
    var a: [64]u8 = undefined;
    var b: [64]u8 = undefined;
    for (0..20000) |it| {
        const u: i128 = if (it < edges.len * 8) edges[it % edges.len] else switch (it % 4) {
            0 => rnd.int(i128) >> @intCast(rnd.uintLessThan(u8, 127)),
            1 => rnd.int(i64),
            2 => rnd.intRangeAtMost(i128, -100000, 100000),
            else => rnd.int(i128) >> 1,
        };
        const scale: u8 = if (it < edges.len * 8) @intCast(it / edges.len * 5) else rnd.uintAtMost(u8, 38);
        var wa = std.Io.Writer.fixed(&a);
        var wb = std.Io.Writer.fixed(&b);
        try writeDecimalReference(&wa, u, scale);
        try writeDecimal(&wb, u, scale);
        try testing.expectEqualStrings(wa.buffered(), wb.buffered());
    }
}

test "formatDecimal pads sub-unit magnitudes, zero, and negatives" {
    var ar = std.heap.ArenaAllocator.init(testing.allocator);
    defer ar.deinit();
    const a = ar.allocator();
    try testing.expectEqualStrings("-0.005", try formatDecimal(a, -5, 3));
    try testing.expectEqualStrings("0", try formatDecimal(a, 0, 0));
    try testing.expectEqualStrings("0.00", try formatDecimal(a, 0, 2));
    try testing.expectEqualStrings("7", try formatDecimal(a, 7, 0));
}

test "binary decimals: both layouts at every width, too wide refused" {
    const Case = struct { []const u8, ?i128 };
    const be = [_]Case{
        .{ &.{}, 0 },                                            .{ &.{0x7F}, 127 },
        .{ &.{0x80}, -128 },                                     .{ &.{ 0x00, 0x80 }, 128 },
        .{ &.{ 0xFF, 0x7F }, -129 },                             .{ &(.{0xFF} ** 8), -1 },
        .{ &(.{0x00} ++ .{0xFF} ** 8), 0xFFFF_FFFF_FFFF_FFFF },  .{ &(.{0xFF} ** 20), -1 },
        .{ &(.{0x7F} ++ .{0xFF} ** 15), std.math.maxInt(i128) }, .{ &(.{ 0x01, 0x00 } ++ .{0x00} ** 15), null },
    };
    for (be) |c| try testing.expectEqual(c[1], bigEndianDecimal(c[0]));
    try testing.expectEqual(@as(?i128, 12345), signMagnitudeDecimal(true, &.{ 0x39, 0x30, 0, 0 }));
    try testing.expectEqual(@as(?i128, -12345), signMagnitudeDecimal(false, &.{ 0x39, 0x30, 0, 0 }));
    try testing.expectEqual(@as(?i128, null), signMagnitudeDecimal(true, &(.{0xFF} ** 16)));
    try testing.expectEqual(@as(?i128, null), signMagnitudeDecimal(true, &(.{0x00} ** 17)));
    try testing.expect(withinPrecision(999, 3) and !withinPrecision(1000, 3) and !withinPrecision(-1000, 3));
}

test "decimal rejects what it cannot read instead of inventing a number" {
    try testing.expectEqual(@as(i128, 100000), parse("1000.00").?.unscaled);
    try testing.expectEqual(@as(u8, 2), parse("1000.00").?.scale);
    try testing.expectEqual(@as(i128, -5), parse("-5").?.unscaled);
    try testing.expectEqual(@as(i128, 7), parse("+7").?.unscaled);
    try testing.expectEqual(@as(i128, 25), parse(".25").?.unscaled);
    for ([_][]const u8{ "1000,00", "1.234,56", "1,2,3", "abc", "1.2.3", "12 34", "", "-", "R$ 10" }) |s| {
        try testing.expect(parse(s) == null);
    }
}
