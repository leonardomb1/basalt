//! A single scalar value, used for literals, parameters, and per-cell access out
//! of columns. The columnar store (see `column.zig`) is the hot path; `Value` is
//! the boxed, one-at-a-time view used at cold edges and in tests.
//!
//! `Decimal` is exact, `unscaled * 10^-scale`. Its i128 field is `align(8)` on
//! purpose: natural 16-byte alignment would size the whole `Value` union at 48
//! bytes, so every bool and i64 would pay for a decimal it does not hold; relaxed,
//! `Value` is 32 bytes, and x86 handles the unaligned access on a cold path.
//!
//! `pow10_table` lives here because both `column` and `eval` depend on this module.
//! It is generated by the repeated multiplication the old runtime loop did, so each
//! entry is bit-identical to what that loop returned; it exists because
//! `keyhash.hashValue` folds every decimal key through `Decimal.keyF64` per row.
//!
//! `Threshold` is the live top-N bound shared between a TopN operator and a source
//! that can skip blocks (currently parquet). The operator publishes the K-th value;
//! a source skips regions whose statistics prove they hold nothing better. Until
//! `full` (the heap holds K entries) every region can contribute, and comparisons
//! must be strict, since a region whose extreme equals the bound may hold ties.

const std = @import("std");

pub const Decimal = struct {
    unscaled: i128 align(8),
    scale: u8,

    pub fn toF64(self: Decimal) f64 {
        return @as(f64, @floatFromInt(self.unscaled)) / pow10f(self.scale);
    }

    /// The f64 a decimal hashes and meets a float as. Equal decimals at any scale
    /// give the same bits: exact operands divide to the one correctly rounded
    /// quotient, and anything wider is reduced to its shortest scale first.
    pub fn keyF64(self: Decimal) f64 {
        const exact_int: i128 = 1 << 53;
        if (self.scale <= 22 and self.unscaled < exact_int and self.unscaled > -exact_int) return self.toF64();
        var d = self;
        while (d.scale > 0 and @rem(d.unscaled, 10) == 0) {
            d.unscaled = @divTrunc(d.unscaled, 10);
            d.scale -= 1;
        }
        return d.toF64();
    }

    /// Exact order: the lower scale is raised to the higher in i256. A side that
    /// overflows doing so is larger in magnitude than any i128, so its sign decides.
    pub fn order(a: Decimal, b: Decimal) std.math.Order {
        if (a.scale == b.scale) return std.math.order(a.unscaled, b.unscaled);
        const up_a = a.scale < b.scale;
        const diff: u8 = if (up_a) b.scale - a.scale else a.scale - b.scale;
        const raised: i128 = if (up_a) a.unscaled else b.unscaled;
        if (diff < 39) if (std.math.mul(i128, raised, pow10_i128[diff])) |r| {
            return if (up_a) std.math.order(r, b.unscaled) else std.math.order(a.unscaled, r);
        } else |_| {};
        const other: i256 = if (up_a) b.unscaled else a.unscaled;
        const big: i256 = if (diff < pow10_i256.len)
            std.math.mul(i256, raised, pow10_i256[diff]) catch @as(i256, std.math.sign(raised)) * std.math.maxInt(i256)
        else if (raised == 0) 0 else @as(i256, std.math.sign(raised)) * std.math.maxInt(i256);
        return if (up_a) std.math.order(big, other) else std.math.order(other, big);
    }
};

/// A DECIMAL of at most 18 digits as its column stores it (`column.Column.Data.dec64`):
/// the unscaled value alone, at the scale the column's type names. A type of its own,
/// not `i64`, so code generic over storage cannot read it as an integer by accident.
pub const Dec64 = enum(i64) {
    _,

    pub const max_precision = 18;

    pub inline fn of(u: i64) Dec64 {
        return @enumFromInt(u);
    }

    pub inline fn int(self: Dec64) i64 {
        return @intFromEnum(self);
    }

    pub inline fn at(self: Dec64, scale: u8) Decimal {
        return .{ .unscaled = self.int(), .scale = scale };
    }

    /// `d` stored at `scale`: raised exactly, or lowered only when no digit is lost;
    /// null when it would round or not fit.
    pub fn fit(d: Decimal, scale: u8) ?Dec64 {
        var u = d.unscaled;
        if (d.scale < scale) {
            const diff = scale - d.scale;
            if (diff >= pow10_i128.len) return if (u == 0) of(0) else null;
            u = std.math.mul(i128, u, pow10_i128[diff]) catch return null;
        } else if (d.scale > scale) {
            const diff = d.scale - scale;
            if (diff >= pow10_i128.len) return if (u == 0) of(0) else null;
            if (@rem(u, pow10_i128[diff]) != 0) return null;
            u = @divExact(u, pow10_i128[diff]);
        }
        return of(std.math.cast(i64, u) orelse return null);
    }
};

pub const pow10_i128 = blk: {
    var t: [39]i128 = undefined;
    var r: i128 = 1;
    for (&t) |*e| {
        e.* = r;
        r *%= 10;
    }
    break :blk t;
};

pub const pow10_i256 = blk: {
    var t: [76]i256 = undefined;
    var r: i256 = 1;
    for (&t) |*e| {
        e.* = r;
        r *= 10;
    }
    break :blk t;
};

const pow10_table = blk: {
    var t: [39]f64 = undefined;
    var r: f64 = 1;
    for (&t) |*e| {
        e.* = r;
        r *= 10;
    }
    break :blk t;
};

pub fn pow10f(n: u8) f64 {
    if (n < pow10_table.len) return pow10_table[n];
    var r: f64 = pow10_table[pow10_table.len - 1];
    var k: u8 = pow10_table.len - 1;
    while (k < n) : (k += 1) r *= 10;
    return r;
}

pub const Threshold = struct {
    column: []const u8 = "",
    desc: bool = false,
    nulls_first: bool = false,
    full: bool = false,
    value: Value = .null,
};

pub const Value = union(enum) {
    null,
    bool: bool,
    int: i64,
    float: f64,
    decimal: Decimal,
    string: []const u8,
    bytes: []const u8,
    date: i32,
    time: i64,
    timestamp: i64,

    pub fn isNull(self: Value) bool {
        return self == .null;
    }
};

test "Dec64.fit moves a decimal to a scale only when no digit is lost and an i64 holds it" {
    const D = Decimal;
    try std.testing.expectEqual(@as(i64, 150), Dec64.fit(D{ .unscaled = 15, .scale = 1 }, 2).?.int());
    try std.testing.expectEqual(@as(i64, 15), Dec64.fit(D{ .unscaled = 1500, .scale = 3 }, 1).?.int());
    try std.testing.expectEqual(@as(i64, -7), Dec64.fit(D{ .unscaled = -7, .scale = 0 }, 0).?.int());
    try std.testing.expect(Dec64.fit(D{ .unscaled = 1505, .scale = 3 }, 2) == null);
    try std.testing.expect(Dec64.fit(D{ .unscaled = std.math.maxInt(i64), .scale = 0 }, 1) == null);
    try std.testing.expect(Dec64.fit(D{ .unscaled = @as(i128, std.math.maxInt(i64)) + 1, .scale = 2 }, 2) == null);
    try std.testing.expectEqual(@as(i64, 0), Dec64.fit(D{ .unscaled = 0, .scale = 60 }, 2).?.int());
    try std.testing.expect(Dec64.fit(D{ .unscaled = 1, .scale = 0 }, 60) == null);
    try std.testing.expectEqual(D{ .unscaled = 1234, .scale = 2 }, Dec64.of(1234).at(2));
}
